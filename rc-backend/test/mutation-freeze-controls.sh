#!/bin/bash
# controls-for: test/mutation-controls.py
# 変異の走行が、**走っている最中の編集で汚れない**か。
#
# ── なぜ在るか(2026-08-03、実際に汚れた)────────────────────────────────────
# 197 件の本走行は 3 時間半かかる。`test/mutation-controls.py` の `copy_tree()` は
# 変異 1 件ごとに**その時の**作業ツリーを写していたので、その間に同じ repo を触ると
# 前半と後半で違う木を測る。実際に 10 file 触っていて、そのうち 1 つが repo 自身の
# 散文規則(`test/no-linerefs.test.mjs`)に触れて `npm test` を赤にした。
#
# 判定は `if ufail or efail: 検出` なので、それ以降の変異は**全部「検出」**になる ——
# 変異を殺したからではなく、無関係な検査が落ちていたから。**素通り(検査の穴)が
# 丸ごと隠れ、要約は「素通り: なし」と書く** = 緑の方向に壊れる。log の進捗行は
# 同じ形のまま並ぶので、外から境目が見えない。経緯 =
# `.harness/evidence-2026-08-03/mutation-run-contaminated.md`。
#
# ── 何を見分けているか(ここが設計の肝)────────────────────────────────────
# 走行中にわざと手元の木を赤にして、
#   ① 走行が汚れない(= 凍結が効いている)
#   ② 要約が「手元の木が動いた」と**名指しで**言う
# の 2 つを見る。
#
# ★見分けに `M85` を使う理由: M85 は**注記つき**(到達しないと実測済み)なので、
#   正常なら「未到達(注記)」。凍結が破れて手元の赤を拾えば `npm test` が落ちて
#   「★注記を外せる」に化ける。**そこが discriminator**。
#   最初 `M1` で測ろうとして、測れない事に気付いた —— 普段から検出される変異では
#   凍結が効いていても破れていても同じ「検出」になり、区別が付かない。
#   「赤が出るか」ではなく「**どちらの理由で赤か**を見分けられるか」で的を選ぶ事。
#
# ★手元を赤にする細工の綴りは**連結で組み立てる**。生の literal をこの file に書くと
#   `no-linerefs` の走査に自分が引っ掛かって、対照を置いた事で本体が赤くなる
#   (この repo で 3 回踏んでいる形)。
#
# ── この対照が**赤にもなる**事の実測(2026-08-04)────────────────────────────
# 緑しか見た事の無い門は、守っている様に見えるだけで測れていない(DESIGN 2.37)。
# 木を写して凍結を壊すと、狙い通り①**だけ**が落ちた:
#
#   | 木                 | 結果                  | ① の行                          |
#   | そのまま           | pass=6 fail=0 / rc=0  | 未到達(注記)                    |
#   | 凍結を壊した写し   | pass=5 fail=1 / rc=1  | ★注記を外せる = 手元の赤を拾った |
#
# 再現(所要 約 3 分):
#   SB=$(/usr/bin/mktemp -d /tmp/freezeneg.XXXXXX)
#   /usr/bin/rsync -a --exclude node_modules --exclude .git <repo>/rc-backend/ "$SB/rc/"
#   $SB/rc/test/mutation-controls.py の  shutil.copytree(FROZEN, dst)  を
#     shutil.copytree(SRC, dst, ignore=shutil.ignore_patterns("node_modules", ".git"))
#   に替えて(= 凍結を壊して)  /bin/bash "$SB/rc/test/mutation-freeze-controls.sh"  → rc=1
#
# ★常設にはしない(1回 150 秒 x 2 = 全掃きが倍になる)。**この注記が測定の記録**である。
#   凍結の実装(`copy_tree` の写し元)を触った時は、上を回してから緑と言う事。
#
# 終了コード: 0=緑 / 1=赤 / 2=未測定。
set -u
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 2

PROBE="$ROOT/tools/_freeze-probe.sh"
OUT="$(/usr/bin/mktemp -t freeze-ctl)" || exit 2
# 模擬の走行に掴ませる印(下の注記を読む事)。片付けで一緒に消す。
MUTLOCK="$(/usr/bin/mktemp -t freeze-mutlock)" || exit 2
/bin/rm -f "$MUTLOCK"   # 走行自身に作らせる。空 file が先に在ると「壊れた印」に見える
cleanup() { /bin/rm -f "$PROBE" "$OUT" "$MUTLOCK"; }
trap cleanup EXIT

pass=0; fail=0
ok(){ pass=$((pass+1)); printf '  OK %s\n' "$1"; }
ng(){ fail=$((fail+1)); printf '  NG %s\n     期待[%s] 実際[%s]\n' "$1" "$2" "$3"; }

echo "── 走行中に手元を赤にして、凍結が効いているかを見る(実測 80〜160 秒)──"
echo "   汚す時機は固定の待ち時間ではなく、走行自身の出力(凍結の行 / 進捗行)で決める"

# 走行が既に動いているなら測れない(同じ台本が 2 本走ると木の写しが競る)。
_mrl=0; bash "$ROOT/tools/mutation-run-live.sh" 2>/dev/null || _mrl=$?
# 丁度 1(居ないと確認できた)の時だけ走行を起こす。2 は「居ない」ではないので、
# そこで起こすと 2 本目の走行になる —— それが 2026-08-02 夜に実際にやった事である。
if [ "$_mrl" -ne 1 ]; then
    if [ "$_mrl" -eq 0 ]; then
        echo "★別の変異走行が動いている。この対照は走行を1本起こすので、今は測れない"
        echo "FREEZE-CONTROLS: 未測定(別の走行が動いている)= **緑ではない**"
    else
        echo "★走行の有無を測れなかった(mutation-run-live.sh exit=${_mrl})。2 本目を起こしかねないので測らない"
        echo "FREEZE-CONTROLS: 未測定(走行の有無が不明)= **緑ではない**"
    fi
    exit 2
fi

# ── ここに「残った細工を掃く」を足しかけて、測った結果やめた(2026-08-05)──────────
# 2026-08-05 に、上の PROBE が指す細工の file が木に居るのを見付け、「trap は SIGKILL を
# 拾えないから前回の残骸だ」と読んで掃除を足しかけた。**誤診だった。**
# (この注記が細工の名前を backtick で引かないのは意図的 —— あれは走行中しか存在しない
#  ので、引くと「実在する名前を引く」門 no-linerefs.test.mjs が正しく赤になる。実際なった。)
# 実際は、その時 `run-controls.sh` が背景で走っていて、この対照が**現に走っている最中**
# だった(log 47 行目まで書かれる前の 22 行目を最終結果として読んだのが元の誤り)。
# つまり見えた file は残骸ではなく**生きている細工**。
#
# だから掃除は入れない。理由は 2 つ、後者の方が重い:
#   (a) SIGKILL で残った実例を**一度も観測していない**。上の trap は EXIT/INT/TERM を拾う。
#   (b) 掃除を置くと、**居るのが生きた細工だった時に消しに行く**。今は上の同時走行の門が
#       止めてくれるが(細工が在る時は必ず走行も生きているので `_mrl` が 1 にならない)、
#       門が将来緩んだ瞬間に、観測した事のない故障の防御が、実在する故障に変わる。
# 残骸が実際に出たら、その観測値を添えてここに足す事。
#
# ── 汚す時機を「時間」ではなく**走行の状態**で決める(2026-08-04 に直した)────────
# 直す前は固定の `/bin/sleep 85` だった。85 は**この機械の今の速さ**に合わせた数で、
# 速い機械では M85 の写しが先に済み(汚しても写しに入らないので、凍結が壊れていても
# 緑)、遅い機械では対照1の最中に汚す(手前で die = 未測定)。**どちらも外から
# 区別が付かない** —— 緑が「見分けた」なのか「間に合わなかった」なのか言えない検査は、
# 検査の顔をした未測定である。実測でも 85 は外れていた: `--only M85` の走行は
# 全部で 76〜91 秒しかかからないので、85 秒の待ちは**走行が終わった後**に落ちる事がある。
#
# 要るのは 2 つだけ:
#   (a) 汚すのが**凍結の後**である事 —— 前だと FROZEN に細工ごと入って全部が壊れる
#   (b) 汚すのが **M85 の写しより前**である事 —— 後だと凍結が壊れていても写しに入らず、
#       緑が「凍結が効いた」ではなく「間に合わなかった」になる
#
# ★最初は「対照2の写しが disk に在る間」を窓にしたが、**測ったら使えなかった**。
#   0.3 秒刻みで 188 回覗いて、canary を持つ写しが見えたのは **1 回だけ**(実測
#   2026-08-04: 対照1の写しは 46 秒生きるのに、対照2の写しは 1 秒未満で消える)。
#   1 秒の poll では構造的に取り逃がす。**目印は「短く光る物」ではなく「一度出たら
#   残る物」から選ぶ事** —— disk 上の一時 dir は前者、走行の stdout は後者である。
#
# 今の目印は走行自身の stdout:
#   (a) = 凍結の行が出た後に汚す。この行は `shutil.copytree(SRC, FROZEN)` の**後**に
#         出るので、見えた時点で FROZEN はもう確定している。
#   (b) = 汚した**直後**に、進捗行 `[n/N]` がまだ出ていない事を見る。進捗行は
#         `copy_tree()` の直前に出るので、「まだ出ていない」= M85 の写しはまだ、が言える。
#         出ていたら順序を主張できないので **exit 2**(緑にも赤にも丸めない)。
#   他所の走行の残骸に惑わされないという副次効果もある —— 読むのは**自分が起こした
#   process の出力**だけなので、/var/folders に何が残っていても窓を誤読しない。
#
# ★目印は台本から読む(この file 冒頭の規則 (1)「入力は本物の生成元から取る」)。
#   綴りを手で書くと、台本側が変えた時に**窓を見失った事に気付かないまま**毎回 2 を返す。
FREEZE_MARK="$(/usr/bin/grep -oF '木を凍結した' test/mutation-controls.py | /usr/bin/head -1)"
CTLOK_MARK="$(/usr/bin/grep -oF '対照 OK' test/mutation-controls.py | /usr/bin/head -1)"
PROG_FORM="$(/usr/bin/grep -oF '{i}/{len(MUT_RUN)}' test/mutation-controls.py | /usr/bin/head -1)"
if [ -z "$FREEZE_MARK" ] || [ -z "$CTLOK_MARK" ] || [ -z "$PROG_FORM" ]; then
    echo "★台本から窓の目印を読めなかった(凍結=[$FREEZE_MARK] 対照=[$CTLOK_MARK] 進捗=[$PROG_FORM])"
    echo "  台本側の文言が変わった時は、ここを合わせるまで**測れていない**"
    echo "FREEZE-CONTROLS: 未測定(目印が読めない)= **緑ではない**"
    exit 2
fi
# 進捗行は `[n/N]` の形で出る。件数に依らない形で見る(`--only` の当たり方が変わっても
# 「写しが始まった」の判定は生きる)。
PROG_RE='^\[[0-9]+/[0-9]+\]'

/bin/rm -f "$PROBE"
# ★`-u` が要る。stdout を file へ向けると Python は既定でブロックバッファリングになり、
#   走行の出す行がバッファに座ったまま出てこない。合図で待ち合わせる以上、
#   「まだ来ない」と「もう過ぎた」が区別できない状態にしてはいけない。
# ★走行の印は砂場へ(2026-08-04)。ここで走らせるのは凍結の窓を覗く為の**模擬**で、
#   しかも give_up は途中で畳む。既定の印を掴むと、測っている間だけ本物の配備が
#   塞がり、畳み方によっては印が /tmp に残る。
RC_MUTATION_LOCK="$MUTLOCK" \
    /usr/bin/python3 -u test/mutation-controls.py --only M85 > "$OUT" 2>&1 &
RUN=$!

give_up() {   # give_up <理由>  —— 走行を畳んで未測定で出る
    echo "★$1"
    # SIGINT を使う。TERM だと Python の atexit が走らず、写しが /var/folders に残って
    # **次の走行の窓の目印を汚す**(上の残骸検出に自分で引っ掛かる)。
    /bin/kill -INT "$RUN" 2>/dev/null
    /bin/sleep 3
    /bin/kill "$RUN" 2>/dev/null
    wait "$RUN" 2>/dev/null
    /bin/rm -f "$PROBE"
    echo "FREEZE-CONTROLS: 未測定($1)= **緑ではない**"
    exit 2
}

# (a) 凍結が済むのを待つ。走行が先に終わったらそれも未測定。
FROZE=0
_i=0
while [ "$_i" -lt 300 ]; do
    if /usr/bin/grep -qF "$FREEZE_MARK" "$OUT" 2>/dev/null; then FROZE=1; break; fi
    /bin/kill -0 "$RUN" 2>/dev/null || break
    /bin/sleep 1; _i=$((_i+1))
done
[ "$FROZE" -eq 1 ] || give_up "凍結の行を観測できなかった(走行が先に終わったか、文言が変わった)"

# repo の散文規則に触れる形を**連結で**作る。ここが `npm test` を赤にする細工。
BAD="loop-replan-gate" ; BAD="${BAD}.sh:196"
{
  echo '#!/bin/bash'
  echo "# 出所は ${BAD} を見よ  ← わざと規則を破っている(対照用・自動で消える)"
  echo 'exit 0'
} > "$PROBE"
[ -s "$PROBE" ] || give_up "細工を書けなかった(汚せていないので凍結を試していない)"

# (b) 書き終えた**後**に進捗行がまだ無い事を見る。進捗行は `copy_tree()` の直前に出るので、
#     無い = M85 の写しはまだ = 細工の方が先、と言える。ここで既に出ていたら、細工が
#     写しに入ったかどうかを決められない —— **順序を主張できない測定は未測定**。
#     (向きに注意: 読むのは書いた後なので、遅れて出た分は「間に合わなかった」側に倒れる。
#      緑を作る方向には決して倒れない)
if /usr/bin/grep -qE "$PROG_RE" "$OUT" 2>/dev/null; then
    give_up "汚す前に M85 の写しが始まっていた(細工と写しの前後を決められない)"
fi
echo "  凍結の後・M85 の写しの前に汚した(順序は走行自身の出力で確認)"

wait "$RUN"; rc=$?
o="$(/bin/cat "$OUT")"

# ── ⓪ 汚した後も対照2枚が通った(= 凍結が対照1を手元の赤から守った)──────────
# 細工は**対照1より前**に落ちる。凍結が効いていれば対照1は FROZEN の写しを測るので
# 手元の赤を見ない。効いていなければ対照1が手元の赤を拾って `die` する ——
# つまりこの行の有無そのものが discriminator であって、窓が開いていた事の前提条件ではない。
case "$o" in
    *"$CTLOK_MARK"*) ok "汚した後も対照2枚が通った(凍結が対照1を手元の赤から守った)" ;;
    *) ng "汚した後も対照2枚が通った" "「${CTLOK_MARK}」を含む" \
          "対照1が手元の赤を拾った = 凍結が破れた疑い。ただし**元から木が赤い**時も同じ形になるので、
        見分けは test/copied-tree-controls.sh(実測15秒)で写しの緑を先に確かめる事:
        $(printf '%s' "$o" | /usr/bin/tail -4)" ;;
esac

# ── ① 凍結が効いている: M85 は「未到達(注記)」のまま ────────────────────
case "$o" in
    *"★注記を外せる"*)
        ng "凍結が効いている(M85 が注記のまま)" "未到達(注記)" "★注記を外せる = 手元の赤を拾った" ;;
    *"未到達(注記)"*)
        ok "凍結が効いている(M85 が注記のまま = 手元の赤を拾っていない)" ;;
    *)
        ng "凍結が効いている(M85 が注記のまま)" "未到達(注記) を含む" "$(printf '%s' "$o" | /usr/bin/tail -4)" ;;
esac
[ "$rc" -eq 0 ] && ok "走行の終了コード 0" || ng "走行の終了コード 0" "0" "$rc"

# ── ② 木が動いた事を名指しで言う ────────────────────────────────────────
case "$o" in
    *"走行中に手元の木が"*) ok "手元の木が動いた事を言う" ;;
    *) ng "手元の木が動いた事を言う" "「走行中に手元の木が」を含む" "$(printf '%s' "$o" | /usr/bin/tail -4)" ;;
esac
case "$o" in
    *"tools/_freeze-probe.sh"*) ok "動いた file を**名指しで**出す(hash では何も分からない)" ;;
    *) ng "動いた file を名指しで出す" "tools/_freeze-probe.sh を含む" "$(printf '%s' "$o" | /usr/bin/tail -4)" ;;
esac

# ── ③ 細工が残っていない ────────────────────────────────────────────────
/bin/rm -f "$PROBE"
[ -e "$PROBE" ] && ng "細工を片付けた" "不在" "残っている: $PROBE" || ok "細工を片付けた(不在を確認)"

echo ""
echo "FREEZE-CONTROLS: pass=$pass fail=$fail"
[ "$fail" -eq 0 ] || exit 1
exit 0
