#!/bin/bash
# commit-msg-guard.sh — commit 文が**書いた通りに保存されたか**を確かめる。2026-08-26 新設。
#
# なぜ要るか(1日に3回踏んだ)
#   commit 文を `python3 -c "..."` の**二重引用符の中**で組み立てると、本文のバッククォートが
#   **コマンド置換として走る**。実測(2026-08-26): `X ` + バッククォート付き → `X THIS_RAN`。
#   `07cd105` では検査名 / `controls-for:` / `BackendSession.interactiveTimeout` が消えた ——
#   どれも**その commit を後から読む人が一番必要とする識別子**。
#
#   ★症状が出ない。commit は成功し、門も通り、緑のまま履歴に入る。
#   ★★**痕跡も残らない。** 開き・閉じ・中身が丸ごと結果へ置き換わるので、
#     「残ったバッククォートを数える」検出は**必ず外す**(最初にそう書いて実際に外した)。
#
# だから此処は**事故の跡を探さない。事故が起き得ない形を強制する**:
#   commit 文は **Write ツールで書いた file から** `git commit -F` で渡す。
#   shell の展開を一度も通らなければ、置換は起こりようが無い。
#
# 使い方:
#   commit-msg-guard.sh <file>   その file を commit 文として渡してよいか見る
#
# 見る事:
#   1. file が**実在して空でない**(`-F` に空を渡すと commit が黙って中断する)
#   2. **中身の空のバッククォート対** `` が無い(置換の跡として残る唯一の形)
#   3. 1 行目が要約として使える長さ(空行 / 100 文字超は履歴が読みにくい)
#   4. ★**行末が助詞で切れていない**。置換で語が消えると
#      「**据え方が…**。 が」の様に、述語の手前で行が終わる形が残る。
#      日本語の本文でしか効かないので、**当たらなくても赤にしない**(注意として出す)。
#
# 終了コード: 0=渡してよい / 1=渡すな / 2=使い方
set -uo pipefail

f="${1:-}"
case "$f" in
    ""|-h|--help) echo "usage: $0 <commit-message-file>" >&2; exit 2 ;;
esac
[ -f "$f" ] || { echo "★file が無い: $f" >&2; exit 1; }
[ -s "$f" ] || { echo "★file が空: $f(-F に空を渡すと commit が黙って中断する)" >&2; exit 1; }

bad=0

# 2. 中身が空のバッククォート対 —— 置換が跡を残す唯一の形。
if grep -qF '``' "$f"; then
    echo "★中身の空の \`\` が在る(置換で語が消えた跡):" >&2
    grep -nF '``' "$f" | head -3 | sed 's/^/    /' >&2
    bad=1
fi

# 3. 1 行目
head1="$(head -1 "$f")"
if [ -z "$head1" ]; then
    echo "★1 行目が空(要約が無い commit は git log で読めない)" >&2; bad=1
elif [ "${#head1}" -gt 100 ]; then
    echo "注意: 1 行目が ${#head1} 文字(100 超)。要約として長い。" >&2
fi

# 4. ★**助詞の署名は捨てた。** 2 度書いて 2 度とも外した:
#    1 度目「残ったバッククォートを数える」→ 事故は痕跡を残さないので必ず外す。
#    2 度目「行末が助詞で終わる行を探す」→ **正常な日本語の本文にも当たる**ので
#           赤の根拠にできない(実測: 無傷の commit でも 3 行当たった)。
#    3 度目は打たない。**検出をやめて、経路を固定する**。
#
#    経路の固定 = この guard を通した file だけを `-F` に渡す、という運用ではなく、
#    **guard 自身が file の出所を見る**。shell の展開を通った file は、通っていない file と
#    区別が付かない —— だから見るのは「**この file が今この瞬間、書いた通りか**」ではなく、
#    「**渡す前に人(私)が中身を目で確かめる機会を1度作ったか**」。
#    その機会 = 下の要約表示。読まずに通す事は出来るが、読めば消えた識別子は目に付く。
#    ★機械が保証できるのは此処までで、それを保証と偽らない。
echo "--- 渡す本文の要約(消えた識別子はここで目に付く)---" >&2
printf '  1行目 : %s\n' "$head1" >&2
printf '  行数   : %s / 文字数 : %s\n' "$(wc -l < "$f" | tr -d ' ')" "$(wc -c < "$f" | tr -d ' ')" >&2
printf '  ` の数 : %s(コード名を書いたなら偶数の筈)\n' \
    "$(tr -cd '`' < "$f" | wc -c | tr -d ' ')" >&2

if [ "$bad" -ne 0 ]; then
    echo "" >&2
    echo "直し方: **Write ツールで書き直す**。shell(python3 -c \"...\" / heredoc)を" >&2
    echo "  通して組み立てると、本文のバッククォートがコマンド置換として走る。" >&2
    exit 1
fi
echo "commit 文として渡してよい: $f"
exit 0
