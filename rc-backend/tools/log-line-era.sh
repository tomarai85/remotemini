#!/bin/bash
# log-line-era.sh — 「其のログ行は**今 走っている実装**が書いた物か」を決める。
#
# ── なぜ別の file か(2026-08-31)──────────────────────────────────────────
# 此の判定は `delivery-check.sh` の中に在ったが、**20 分で2回 壊れた**:
#   1回目 判定そのものを書き忘れた —— 「配ってある file は直っているか」と
#         「走っている process は其れより新しいか」は書いたのに、
#         **既に書かれている行**が古い実装の産物である事を見ていなかった。
#         配備した直後は必ず其の状態で、実際に直後の走行が偽の差
#         「1 < 105 = 104 ビルド進む」を復活させた。
#   2回目 `date -j` に `-u` が無く、UTC の刻を手元の時間帯(CDT)として読んでいた。
#         行の刻が**未来**になるので `行 < 起動` が構造的に真にならず、
#         門が在るのに一度も閉じない形だった(実測で 5 時間ずれ)。
# どちらも「生きた机への ssh が要る」道具の中に埋まっていたので、対照が書けなかった。
# **判定だけを引き剥がせば、机が無くても撃てる。**
#
# ★何を答え、何を答えないか
#   答える  = 其の刻が「今の走行が始まった後」か
#   答えない= 版が正しいか / 電話が新しいか(呼ぶ側の仕事)
#
# 使い方:
#   log-line-era.sh <起動 epoch> <行の刻 ISO8601(末尾 Z)> [今 epoch]
# 終了コード:
#   0 = 今の走行が書いた行(そのまま読んでよい)
#   2 = 今の走行より前の行(欄の意味が違うかもしれない)
#   3 = 刻を読めない(空 / 形が違う / 未来)= 判らない。0 に丸めない
set -uo pipefail

BOOT="${1:-}"
SEEN="${2:-}"
NOW="${3:-$(date +%s)}"

num() { case "${1:-}" in ''|*[!0-9]*) printf '' ;; *) printf '%s' "$1" ;; esac; }

BOOT="$(num "$BOOT")"
NOW="$(num "$NOW")"
if [ -z "$BOOT" ] || [ -z "$NOW" ]; then
    echo "log-line-era: 起動 epoch か今の epoch が数字でない = 判らない" >&2
    exit 3
fi
if [ -z "$SEEN" ]; then
    echo "log-line-era: 行の刻が空 = 判らない" >&2
    exit 3
fi

# ★`-u` は落とせない。ログの刻は UTC(`…Z`)で、`date -j` の既定は手元の時間帯。
#   秒より下(`.766`)と末尾の `Z` は落としてから渡す。
SEEN_EPOCH="$(date -u -j -f '%Y-%m-%dT%H:%M:%S' "${SEEN%%.*}" +%s 2>/dev/null || printf '')"
SEEN_EPOCH="$(num "$SEEN_EPOCH")"
if [ -z "$SEEN_EPOCH" ]; then
    echo "log-line-era: 行の刻を読めない([$SEEN])= 判らない" >&2
    exit 3
fi
# 未来の刻は読み違い。安全側(判らない)へ倒す —— 時間帯を取り違えると必ず此処に落ちる。
if [ "$SEEN_EPOCH" -gt "$NOW" ]; then
    echo "log-line-era: 行の刻が未来になる([$SEEN])= 読み違い。判らない" >&2
    exit 3
fi

if [ "$SEEN_EPOCH" -lt "$BOOT" ]; then
    echo "log-line-era: 其の行は今の走行より前($SEEN)" >&2
    exit 2
fi
exit 0
