// 実機を触る台本(`tools/live-*.mjs`)が返す終了コードの**意味**を1箇所に置く。
//
// ── なぜ1箇所に要るか(2026-08-02 に実際に起きた事)────────────────────────
// 同じ機械を同じ時刻に測った2本が**逆の事を言った**。`tools/live-inject-check.mjs` は
// exit 3(相手が上限で答えていない)、`tools/live-http-check.mjs` は「16 OK / 0 NG / exit 0」。
// 後者の緑は嘘ではない —— 運ぶ層は本当に通っていた —— が、「一巡した」と読まれる。
// そこで 3 を足した。**足したのは1本だけだった**、というのが此の module の存在理由。
//
// 2026-08-06 に4本を数えたら、`tools/live-choice-check.mjs` だけが上限を知らないままだった
// (`failed ? 1 : 0` で、上限の画面はただの赤)。しかも其処の注釈は「上限や信頼確認の
// 可能性」と**2つの状態を束ねて**いて、これは inject 側が 8/02 に解いた束ねと同じ形。
// 教訓を1本に適用して他へ運ばない、という此の repo が何度も踏む型そのもの。
//
// ── 意味(この4つ以外を足さない)──────────────────────────────────────────
//   0 = 全部通った
//   1 = 測って、どれかが赤い。**直す物が在る**
//   2 = 準備段で中断。**何も測れていない**(1 と混ぜない。混ぜると直す物を探して空振りする)
//   3 = 運ぶ層は通ったが、相手が答えていない(利用上限)。**直す物は無い、待つ**
//
// ── 順序(2 > 1 > 3 > 0)とその理由 ──────────────────────────────────────
//   2 が最優先 : 何も測れていない回に、測った結果の顔をさせない。
//   1 が 3 より先 : 直せる物を先に見せる。上限は「送れない」ではないので、運ぶ層の赤は
//                   上限では説明が付かない = 本物の欠陥。だから上限で隠さない。
//                   ★逆に、上限で赤くなり得る枝(相手の返答に依る検査)は、各台本の側で
//                     check ではなく note へ倒してある。倒し忘れると此の順序が牙を剥く
//                     ——「待てば直る物」を「直す物」として報告する計器になる。
//
// 8 通り全部と、4本の台本が此の意味に合意しているかは `test/live-exit-codes.test.mjs`。

/**
 * @param {{prepAbort?: boolean, failed?: boolean, limitedReply?: boolean}} f
 * @returns {0|1|2|3}
 */
export function exitCodeFor({ prepAbort = false, failed = false, limitedReply = false } = {}) {
  return prepAbort ? 2 : failed ? 1 : limitedReply ? 3 : 0;
}

/** 読み手向けの1行。台本の最後に出す文言を揃える為(数字だけ出しても次の手が判らない)。 */
export const EXIT_MEANING = Object.freeze({
  0: "全部通った",
  1: "測って、どれかが赤い(直す物が在る)",
  2: "準備段で中断(何も測れていない)",
  3: "運ぶ層は通ったが相手が答えていない(利用上限。待つ)",
});
