#!/bin/bash
# 変異の**的**が今のコードに当たるかを commit の直前に確かめる。
#
# なぜ要るか(2026-08-02、実際に踏んだ):
#   `server.mjs` の `readHead` を `readBranchHead` へ**改名しただけ**で、変異 W9 の的が外れた。
#   的は本文を文字列で探すので、改名・整形・行の入れ替えは**検査の的を静かに無効化する**。
#   外れた的は走行すると「対象行が無い」で赤になるが、それが分かるのは **30〜85 分後**。
#   commit の時点では `npm test` も e2e も全部緑なので、**人の目で気付ける材料が1つも無い**。
#   `--dry` は 34ms で答えるのに、それを**呼ぶ物が無かった**のが唯一の穴だった。
#
# 対照(この検査が赤にもなる事の確認): `test/mutation-target-controls.sh`
# 本体はここ(追跡される)。`.git/hooks/pre-commit` は clone に付いてこない薄い呼び口。
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# ★★ここに「走行中は commit を止める」を置いていたが、**前提が事実と違った**ので外した
#   (2026-08-02 17:1x)。書いていた理由は「走行中は `src/` が意図的に壊れているので
#   `--dry` が嘘の赤を出す / commit すると変異が混ざった木を記録する」だった。
#   **どちらも起きない。** 変異台本は本物の木を書き換えない:
#     test/mutation-controls.py  d = tempfile.mkdtemp(prefix="mut-")
#                                shutil.copytree(SRC, dst, ...)
#     同                         subprocess.Popen(cmd, cwd=cwd)  # cwd は複製の中
#   実測(走行 38/119 の最中):
#     - `--dry` → 「的の照合: 112件 / 当たらない 0件」= 正確。嘘の赤は出ない
#     - 走行中の node の cwd = /private/var/folders/.../T/mut-yt53i0bl/rc(lsof) = 複製の中
#     - `git diff --stat -- src/` に出るのは自分の H2 差分だけで、変異の痕跡は無い
#   つまりこの門は**何も守っていないのに 85 分間 commit を塞いでいた**。
#   実害も出た: この日の H2 の仕事が、その窓の間ずっと記録できなかった。
#   ★教訓: 門を作る時、止める理由を**測ってから**書く。「壊れている最中だから」は
#   もっともらしいが、壊れているのは複製の方だった(method_measure_where_the_system_actually_reads)。
#
#   本当に守るべき事は別に在った = **走行中に `src/` を編集しない**事。
#   台本が変異ごとに手元の木を写し直していたので、途中で書き換えると前半と後半で
#   違う木を測る事になり、走行の結果が混ざった。実際 8/03 に 3h17m の走行が丸ごと
#   これで嘘になった(1 file が `no-linerefs` を割り、以後の全変異が別の理由で「検出」)。
#
# ★2026-08-03 追記 —— **この注意書きはもう嘘**。同日の直しで、台本は開始時に木を
#   temp へ凍結し、全変異は凍結側から複製する様になった(`_FROZEN_HOLDER` / `copy_tree`)。
#   走行中の編集はもう結果を汚さない —— 凍結が買ったのはまさにその自由。
#   古い文言を残すと「正しい走行を、警告を真に受けて捨てる」方向に人を訓練する。
#   守りが実装より 1 版古いと、**逆向きの誤り**を教える。だから文言ごと差し替える。
#
#   凍結の有無を**推測しない**。実装を見て言う: `copy_tree` が `FROZEN` から写しているか。
#   見に行った先が変わっていたら「凍結あり」とは言わない(= 分からないとだけ言う)。
#   ★2026-08-04: 判定は 0/1/2 を返す(2 = 測れなかった)。「走っていない」と言えるのは
#   **丁度 1** の時だけなので、それ以外はこの注意を出す側へ倒す。判らない時に黙るのは、
#   「走っていない」と断言するのと読み手にとって同じである。
# `cmd || rc=$?` の形で取る(裸に置くと `set -e` の台本で死ぬ。warn-ledger.sh の頭を見よ)。
_mrl=0
bash "$ROOT/tools/mutation-run-live.sh" || _mrl=$?
if [ "$_mrl" -ne 1 ]; then
    if [ "$_mrl" -eq 0 ]; then
        _sub="変異の走行が動いている"
    else
        _sub="変異の走行の有無を**測れなかった**(mutation-run-live.sh exit=${_mrl})。走行中かもしれない前提で読む事"
    fi
    if grep -q 'shutil.copytree(FROZEN' "$ROOT/test/mutation-controls.py" 2>/dev/null; then
        echo "注意: ${_sub}。台本は開始時の木を凍結して回すので、" >&2
        echo "  今の編集や commit はその走行の結果を汚さない。走行後の報告に" >&2
        echo "  **動いた file の名前**が出るので、測定に関わるかはそこで判断する事。" >&2
    else
        # ★この行は**一重引用**でなければならない。二重引用の中の逆引用符は
        #   コマンド置換として実行され、`copy_tree` が消えて文が壊れる(実測して直した)。
        echo "注意: ${_sub}。しかも台本が**凍結していない**:" >&2
        echo '  (`copy_tree` の写し元が `FROZEN` ではない)。この状態で `src/` を編集すると' >&2
        echo '  走行の結果が混ざる —— 8/03 に 3h17m がこれで嘘になった。編集は走行の後にする事。' >&2
    fi
    echo "  commit 自体は木を変えないので止めない。検査は続行する。" >&2
fi

# ★★的が「外れる」方だけを見ていた(2026-08-05、実測して塞いだ)。
#
#   `--dry` は的が**当たるか**しか数えない。並びから的を1件削除して回すと
#     「的の照合: 240件 / 当たらない 0件」exit=0
#   で素通りする(241 から1件消して実測)。つまり **欠陥を見張る検査を、欠陥と一緒に
#   消せる**。改名で的が静かに外れるのを捕まえる為に作った門が、的そのものが静かに
#   消えるのは通していた —— 同じ「静かに見張りが減る」の裏返しの側。
#   commit 文に貼る「的は減っていない」の一行が、この穴のせいで**実際には何も
#   保証していなかった**(私自身が今夜それを証拠として引いた)。
#
#   数の写しは持たない。`test/mutation-target-controls.sh` の 3-3 が既に裁いている
#   通り、同じ一覧が2箇所に居ると足す作業が必ず片方を置き去りにする。正本は並びその物
#   なので、**HEAD の同じ file を数え直して**比べる。族の頭文字も命名規則も本体から
#   取り出すので、規則が変わっても両側に同じ訳が当たって差し引き0になる。
_targets_of() {  # stdin = mutation-controls.py の中身 → 並びの件数
    local body; body="$(cat)"
    local fam; fam="$(printf '%s\n' "$body" | sed -n 's/^FAM = "\([A-Z][A-Z]*\)".*/\1/p' | head -1)"
    [ "${#fam}" -ge 3 ] || return 2
    printf '%s\n' "$body" | grep -cE "^ *\(\"[${fam}][0-9]+[a-z]?[ (]"
}
_rel="$(cd "$ROOT" && git ls-files --full-name test/mutation-controls.py 2>/dev/null)"
_now=""; _was=""
[ -n "$_rel" ] && _now="$(_targets_of < "$ROOT/test/mutation-controls.py" 2>/dev/null)"
[ -n "$_now" ] && _was="$(cd "$ROOT" && git show "HEAD:$_rel" 2>/dev/null | _targets_of 2>/dev/null)"
if [ -z "$_was" ] || [ -z "$_now" ]; then
    # 測れなかった(git 外 / 初回 commit / file の改名 / FAM の置き場所が変わった)。
    # 黙って緑にはしない —— 但し commit 自体は木を変えないので止めない(上と同じ判断)。
    echo "注意: 的の**件数**を HEAD と比べられなかった(消えた的は今回検出できない)。" >&2
elif [ "$_now" -lt "$_was" ]; then
    # ★展開は `if` の**外**で済ませる(2026-08-05 に踏んだ)。最初 `${#VAR:-}` と書いたが
    #   長さ `#` と既定値 `:-` は併用できず bad substitution になる。`set -e` が無いので
    #   script は死なず、**`if` が両方の枝を走らせないまま素通りして exit 0** —— 門が
    #   黙って消えた上で「的の照合: 240件 / 当たらない 0件」の緑だけが出た。
    #   門の中で落ちると fail-open になるので、落ちうる式は門の手前に置く。
    _ok="${RC_TARGETS_SHRINK_OK:-}"
    if [ "${#_ok}" -ge 10 ]; then
        echo "的が ${_was} → ${_now} 件に減る事を承知で通す: ${RC_TARGETS_SHRINK_OK}" >&2
    else
        echo "★commit しない: 的が ${_was} → ${_now} 件に**減っている**。" >&2
        echo "  消えた的が見張っていた欠陥は、これ以降**誰も見ていない**。" >&2
        # ★この行も**一重引用**でなければならない(上の 63 行目と同じ罠。二重引用の中の
        #   逆引用符はコマンド置換として走り、`--dry` が消えて文が壊れる)。書いた直後に踏んだ。
        echo '  `--dry` は当たるかしか見ないので、この減りは 0件 の緑として出る。' >&2
        echo '  意図して見張りを降ろすなら、何を降ろすのか書いて通す事:' >&2
        echo '    RC_TARGETS_SHRINK_OK="W98 は field ごと消えたので見張らないと決めた" git commit …' >&2
        echo '  (10文字以上。文言はこの出力に残るので、後から理由を辿れる)' >&2
        exit 1
    fi
fi

out="$(cd "$ROOT" && python3 test/mutation-controls.py --dry 2>&1)"
rc=$?
if [ "$rc" -ne 0 ]; then
    echo "$out" >&2
    echo "" >&2
    echo "★commit しない: 上の変異が**今のコードに当たらない**。" >&2
    echo "  当たらない的は走っても意味が無い = その欠陥はもう誰も見張っていない。" >&2
    echo "  直し方: 改名・整形で本文が変わった側に合わせて test/mutation-controls.py の" >&2
    echo "  探し文を付け替える(消すのは、その欠陥を見張らないと決めた時だけ)。" >&2
    exit 1
fi
echo "$out" | tail -1
exit 0
