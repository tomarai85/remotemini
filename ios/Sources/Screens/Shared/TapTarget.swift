import SwiftUI

/// 片手で押す的の下限(2026-08-08、監査 X2-3。DESIGN.md の 2.66)。
///
/// この repo が守っている一番大きな前提は「これは**移動中に片手で押す道具**」で、
/// それは `REQUIREMENTS.md` の題そのものでもある。にも関わらず、押す物の寸法は
/// 一度も測られていなかった —— 割り込みと送信は `Image` に `.font(.title2)` を
/// 当てただけ、壊れた時に押す「再試行」「読み直す」には `.font(.caption)` が
/// 乗っていた。歩きながら、あるいは電車の揺れの中で押す物の寸法としては、
/// どれも Apple の下限(44pt)を下回っている。
///
/// ── 数を1箇所に置く理由 ────────────────────────────────────────────────────
/// 44 を各所に散らすと、後から「ここだけ 36 でいい」が入った時に**それが判断
/// だったのか写し間違いだったのか**が誰にも判らなくなる。1つの定数に集めれば、
/// 下限を割る的は「この修飾子が当たっていない」という**在る / 無い**の話になる。
enum TapTarget {
    /// Apple HIG の下限。`ios/UITests/TapTargetUITests.swift` はこの値を呼ばずに
    /// 手で 44 と書いている —— 呼んで比べると「同じ定数が同じ値を返す」しか
    /// 言えず、画面に出ている的が本当にその寸法かを測れない。
    static let minimum: CGFloat = 44
}

extension View {
    /// 的を下限まで広げ、**広げた分を本当に押せるようにする**。
    ///
    /// ★`Button` の外ではなく **label の内側**に当てる。外に当てると layout の枠は
    /// 育つのに、押せる領域は label のまま残る事が有る(`Button` の当たり判定は
    /// label 側の形から来る)。`.buttonStyle(.bordered)` の的では更に差が出て、
    /// 外に当てると**見えている枠の外側**が押せる状態になる —— 見た目と当たりが
    /// ずれるので、隣の選択肢との境目が目で判らなくなる。内側に当てれば枠自体が
    /// 育つので、見えている物と押せる物が一致する。
    ///
    /// ★`.contentShape(Rectangle())` は飾りではない。これが無いと `frame` は 44pt を
    /// 名乗るのに、実際に反応するのは**絵柄や文字の上だけ**になる。寸法だけを見る
    /// 検査はその実装で緑のまま通る(既定の `tap()` は中心 = 絵柄の上を叩く)ので、
    /// `TapTargetUITests` は的の**端**を叩く検査を別に1本持っている。
    ///
    /// ★`min` であって固定ではない。選択肢のボタンは折り返して 44pt を超えるし、
    /// 超えて困る物は無い。困るのは下回る事だけ。
    func tapTarget() -> some View {
        frame(minWidth: TapTarget.minimum, minHeight: TapTarget.minimum)
            .contentShape(Rectangle())
    }
}
